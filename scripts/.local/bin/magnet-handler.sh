#!/usr/bin/env bash
# magnet-handler.sh
# POSTs magnet URI to qBittorrent Web UI API, then opens the Web UI
# Distro-agnostic: supports Linux (XDG/GNOME/KDE), macOS, WSL

# --- tput safety wrapper ---
_safe_tput() { command -v tput &>/dev/null && tput "$@" 2>/dev/null; }

red=$(_safe_tput setaf 1) || red='\033[31m'
grn=$(_safe_tput setaf 2) || grn='\033[32m'
ylw=$(_safe_tput setaf 3) || ylw='\033[33m'
cyn=$(_safe_tput setaf 6) || cyn='\033[36m'
bld=$(_safe_tput bold)    || bld='\033[1m'
rst=$(_safe_tput sgr0)    || rst='\033[0m'

# --- paths ---
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/magnet-handler"
config_file="${config_dir}/config"

# --- notify wrapper (graceful fallback to echo) ---
notify() {
    local level="$1"  # info | success | error
    local title="$2"
    local body="$3"
    local urgency="normal"
    local color="$cyn"

    case "$level" in
        success) urgency="normal";   color="$grn" ;;
        error)   urgency="critical"; color="$red" ;;
        *)       urgency="normal";   color="$cyn" ;;
    esac

    if command -v notify-send &>/dev/null; then
        notify-send "$title" "$body" --urgency="$urgency"
    fi
    echo -e "${color}${bld}${title}:${rst} ${body}"
}

# --- dependency checker ---
check_deps() {
    local missing=()
    local required=("curl")
    local optional_browser=("xdg-open" "gio" "kde-open" "kde-open5" "open")
    local found_browser=0

    for cmd in "${required[@]}"; do
        if ! command -v "$cmd" &>/dev/null; then
        missing+=("$cmd")
        fi
    done

    for cmd in "${optional_browser[@]}"; do
        if command -v "$cmd" &>/dev/null; then
        found_browser=1
        break
        fi
    done

    if [[ $found_browser -eq 0 ]] && grep -qi microsoft /proc/version 2>/dev/null; then
        found_browser=1
    fi

    if [[ ${#missing[@]} -gt 0 ]]; then
        notify error "Missing dependencies" "${missing[*]} — install and re-run"
        exit 1
    fi

    if [[ $found_browser -eq 0 ]]; then
        notify error "No browser-open command found" "Install one of: ${optional_browser[*]}"
        exit 1
    fi
}

# --- config generator ---
generate_config() {
    mkdir -p "$config_dir"
    cat > "$config_file" <<'EOF'
# magnet-handler config
# Generated by magnet-handler.sh

# qBittorrent Web UI URL (no trailing slash)
qbit_domain="https://qbit.yourdomain.com"

# qBittorrent Web UI credentials
qbit_user="your_username"
qbit_pass="your_password"
EOF
    chmod 600 "$config_file"
    notify info "Config created" "$config_file — edit it and re-run"
    exit 0
}

# --- config loader ---
load_config() {
    if [[ ! -f "$config_file" ]]; then
        notify info "No config found" "Generating one now..."
        generate_config
    fi

    # shellcheck source=/dev/null
    source "$config_file"

    local missing_vars=()
    for var in qbit_domain qbit_user qbit_pass; do
        local val="${!var}"
        if [[ -z "$val" || "$val" == *"yourdomain"* || "$val" == "your_"* ]]; then
        missing_vars+=("$var")
        fi
    done

    if [[ ${#missing_vars[@]} -gt 0 ]]; then
        notify error "Config incomplete" "Please set: ${missing_vars[*]} in ${config_file}"
        exit 1
    fi

    # derive hostname for reachability check
    qbit_host=$(echo "$qbit_domain" | sed -e 's|[^/]*//||' -e 's|[:/].*||')
}

# --- reachability check ---
check_host() {
    local http_code
    http_code=$(curl -s -o /dev/null -w "%{http_code}" \
        --max-time 5 \
        --header "Referer: ${qbit_domain}" \
        "${qbit_domain}/api/v2/auth/login")

    if [[ "$http_code" == "000" ]]; then
        notify error "Host unreachable" "Could not connect to ${qbit_domain}"
        exit 1
    fi

    # 200 = login page up, 403 = CSRF/auth wall (still reachable)
    # anything other than 000 means the host responded
    notify info "Host reachable" "Got HTTP ${http_code} from ${qbit_domain}"
}

# --- browser open (distro-agnostic) ---
open_browser() {
    local url="$1"
    if command -v xdg-open &>/dev/null; then
        xdg-open "$url"
    elif command -v gio &>/dev/null; then
        gio open "$url"
    elif command -v kde-open &>/dev/null; then
        kde-open "$url"
    elif command -v kde-open5 &>/dev/null; then
        kde-open5 "$url"
    elif command -v open &>/dev/null; then
        open "$url"
    elif grep -qi microsoft /proc/version 2>/dev/null; then
        cmd.exe /c start "" "$url"
    else
        notify error "No browser-open command found" "Open manually: ${qbit_domain}"
        return 1
    fi
}

# --- main ---
check_deps
load_config
check_host

magnet_uri="$1"

if [[ -z "$magnet_uri" ]]; then
    notify error "No magnet URI provided" "Usage: $0 <magnet-uri>"
    exit 1
fi

# Step 1: authenticate — Referer header required for qBit CSRF protection
notify info "qBittorrent" "Authenticating..."
login_response=$(curl -s -i \
    --header "Referer: ${qbit_domain}" \
    --data-urlencode "username=${qbit_user}" \
    --data-urlencode "password=${qbit_pass}" \
    "${qbit_domain}/api/v2/auth/login")

sid=$(echo "$login_response" | grep -o 'SID=[^;]*' | head -1)

if [[ -z "$sid" ]]; then
    notify error "qBittorrent" "Login failed — check credentials in ${config_file}"
    exit 2
fi

# Step 2: POST magnet — Referer header required for qBit CSRF protection
notify info "qBittorrent" "Sending magnet link..."
add_response=$(curl -s -o /dev/null -w "%{http_code}" \
    -X POST \
    --header "Referer: ${qbit_domain}" \
    --cookie "$sid" \
    --data-urlencode "urls=${magnet_uri}" \
    "${qbit_domain}/api/v2/torrents/add")

if [[ "$add_response" != "200" ]]; then
    notify error "qBittorrent" "API returned HTTP ${add_response}"
    exit 3
fi

notify success "Torrent Added" "Opening Web UI to set tags..."

# Step 3: open Web UI
open_browser "${qbit_domain}" || exit 4